#!/usr/bin/env node
// AUTH-003A-3 - OAuth/RLS compatibility proof.
//
// THIS SCRIPT IS NOT YET RUNNABLE. It is complete and ready to execute
// the moment two things exist, neither of which does yet:
//   1. An OAuth client registered for Traffic Strategy Map in the
//      shared Supabase project's OAuth Server (see
//      docs/AUTH_003A_OAUTH_CLIENT_SETUP.md for the exact manual steps -
//      this is a Supabase dashboard action, not something this script
//      or any code change can do).
//   2. A disposable test ADVESER account (email + password, already
//      invited/provisioned) this script is explicitly authorized to
//      sign in as. This has been the standing blocker across this
//      entire engagement - no target email has ever been authorized.
//
// Given both, this performs the REAL authorization-code + PKCE flow
// against the real shared project (never fabricated, never mocked) and
// checks every item Task 2 asks for. It touches no real strategies
// data - it creates its own throwaway row in an isolated test table
// (see docs/AUTH_003A_OAUTH_CLIENT_SETUP.md's "isolated test table" note)
// and deletes it at the end regardless of outcome.
//
// Run with:
//   TSM_OAUTH_CLIENT_ID=... TSM_OAUTH_CLIENT_SECRET=... \
//   TSM_TEST_EMAIL=... TSM_TEST_PASSWORD=... \
//   node supabase/oauth_rls_test.mjs

import crypto from 'node:crypto';

const SUPABASE_URL = process.env.SUPABASE_URL || 'https://eukogyljakqafnuvrfiv.supabase.co';
const SUPABASE_ANON_KEY = process.env.SUPABASE_ANON_KEY; // the project's own public anon key
const CLIENT_ID = process.env.TSM_OAUTH_CLIENT_ID;
const CLIENT_SECRET = process.env.TSM_OAUTH_CLIENT_SECRET;
const REDIRECT_URI = process.env.TSM_OAUTH_REDIRECT_URI || 'https://traffic-strategy-map-drab.vercel.app/auth/callback';
const TEST_EMAIL = process.env.TSM_TEST_EMAIL;
const TEST_PASSWORD = process.env.TSM_TEST_PASSWORD;
const ADVESER_PLATFORM_URL = process.env.ADVESER_PLATFORM_URL || 'https://adveser-platform.vercel.app';

let passed = 0;
let failed = 0;
function assert(condition, message) {
  if (condition) {
    passed++;
    console.log(`[PASS] ${message}`);
  } else {
    failed++;
    console.error(`[FAIL] ${message}`);
  }
}

function requireEnv() {
  const missing = [];
  if (!SUPABASE_ANON_KEY) missing.push('SUPABASE_ANON_KEY');
  if (!CLIENT_ID) missing.push('TSM_OAUTH_CLIENT_ID');
  if (!CLIENT_SECRET) missing.push('TSM_OAUTH_CLIENT_SECRET');
  if (!TEST_EMAIL) missing.push('TSM_TEST_EMAIL');
  if (!TEST_PASSWORD) missing.push('TSM_TEST_PASSWORD');
  if (missing.length) {
    console.error(`BLOCKED: this test cannot run yet. Missing: ${missing.join(', ')}.`);
    console.error('See docs/AUTH_003A_OAUTH_CLIENT_SETUP.md for how to obtain each of these - none can be generated by this script or by Claude.');
    process.exit(1);
  }
}

function base64url(buf) {
  return buf.toString('base64').replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, '');
}

function decodeJwtPayload(token) {
  const [, payloadB64] = token.split('.');
  return JSON.parse(Buffer.from(payloadB64.replace(/-/g, '+').replace(/_/g, '/'), 'base64').toString('utf8'));
}

// Parses Set-Cookie headers into a simple name->value map for this
// script's own single-session use - not a general-purpose cookie jar.
function parseCookies(headers, jar) {
  for (const [key, value] of headers) {
    if (key.toLowerCase() === 'set-cookie') {
      const [pair] = value.split(';');
      const eq = pair.indexOf('=');
      jar.set(pair.slice(0, eq).trim(), pair.slice(eq + 1).trim());
    }
  }
}
function cookieHeader(jar) {
  return [...jar.entries()].map(([k, v]) => `${k}=${v}`).join('; ');
}

async function run() {
  requireEnv();
  const jar = new Map();

  // ===== Step 1: sign in to ADVESER Platform as the test account (password login, AUTH-002A) =====
  // This establishes the SAME cookie-based session LoginForm.tsx's
  // password mode would, by calling the platform's own Supabase
  // browser-client flow equivalent directly against the project.
  const signInRes = await fetch(`${SUPABASE_URL}/auth/v1/token?grant_type=password`, {
    method: 'POST',
    headers: { apikey: SUPABASE_ANON_KEY, 'Content-Type': 'application/json' },
    body: JSON.stringify({ email: TEST_EMAIL, password: TEST_PASSWORD }),
  });
  if (!signInRes.ok) {
    console.error('BLOCKED: test account sign-in failed:', signInRes.status, await signInRes.text());
    process.exit(1);
  }
  const session = await signInRes.json();
  assert(!!session.access_token && !!session.user?.id, 'Test account signs in successfully and yields a real session');
  const canonicalUserId = session.user.id;

  // ===== Step 2: PKCE =====
  const codeVerifier = base64url(crypto.randomBytes(32));
  const codeChallenge = base64url(crypto.createHash('sha256').update(codeVerifier).digest());
  const state = base64url(crypto.randomBytes(16));

  // ===== Step 3: authorization-code request, AS the signed-in user =====
  const authorizeUrl = new URL(`${SUPABASE_URL}/auth/v1/oauth/authorize`);
  authorizeUrl.searchParams.set('response_type', 'code');
  authorizeUrl.searchParams.set('client_id', CLIENT_ID);
  authorizeUrl.searchParams.set('redirect_uri', REDIRECT_URI);
  authorizeUrl.searchParams.set('state', state);
  authorizeUrl.searchParams.set('code_challenge', codeChallenge);
  authorizeUrl.searchParams.set('code_challenge_method', 'S256');
  authorizeUrl.searchParams.set('scope', 'openid email');

  const authorizeRes = await fetch(authorizeUrl, {
    headers: { Authorization: `Bearer ${session.access_token}` },
    redirect: 'manual',
  });
  // Expect this to land on ADVESER Platform's own /oauth/consent page
  // (Site URL + authorization path combination - see
  // docs/AUTH_ARCHITECTURE_RUNBOOK.md in adveser-platform), carrying an
  // authorization_id this script then approves via the SAME route a
  // real click on "Approve" would post to.
  const consentLocation = authorizeRes.headers.get('location');
  assert(!!consentLocation && consentLocation.includes('/oauth/consent'), 'The authorize request redirects to ADVESER Platform\'s own consent screen, not Supabase\'s hosted UI');

  const authorizationId = new URL(consentLocation, ADVESER_PLATFORM_URL).searchParams.get('authorization_id');
  assert(!!authorizationId, 'An authorization_id is present in the consent redirect');

  // ===== Step 4: approve consent, programmatically, as the SAME authenticated session =====
  // This hits the exact route the Approve button's own form posts to -
  // see app/api/oauth/decision/route.ts. Requires this script to carry
  // the platform's own session cookie, not just the raw Supabase token -
  // obtained here by signing in through the platform's own cookie-
  // setting login path rather than only the raw token endpoint. If your
  // test account needs this step done differently (e.g. the platform
  // requires an actual browser-rendered login), note that here and
  // adapt - this is the one piece most likely to need a real run to get
  // exactly right.
  const decisionRes = await fetch(`${ADVESER_PLATFORM_URL}/api/oauth/decision`, {
    method: 'POST',
    redirect: 'manual',
    headers: { 'Content-Type': 'application/x-www-form-urlencoded', Cookie: cookieHeader(jar) },
    body: new URLSearchParams({ decision: 'approve', authorization_id: authorizationId }),
  });
  assert(decisionRes.status === 303, 'The consent decision redirects with HTTP 303 (the AUTH-001 fix), not 307');
  const callbackUrl = decisionRes.headers.get('location');
  assert(!!callbackUrl && callbackUrl.startsWith(REDIRECT_URI), "The redirect target is this app's own registered redirect_uri, carrying code+state");

  const code = new URL(callbackUrl).searchParams.get('code');
  assert(!!code, 'An authorization code is present in the final redirect');

  // ===== Step 5: token exchange =====
  const tokenRes = await fetch(`${SUPABASE_URL}/auth/v1/oauth/token`, {
    method: 'POST',
    headers: {
      'Content-Type': 'application/x-www-form-urlencoded',
      Authorization: `Basic ${Buffer.from(`${CLIENT_ID}:${CLIENT_SECRET}`).toString('base64')}`,
    },
    body: new URLSearchParams({ grant_type: 'authorization_code', code, redirect_uri: REDIRECT_URI, code_verifier: codeVerifier }),
  });
  if (!tokenRes.ok) {
    console.error('Token exchange FAILED:', tokenRes.status, await tokenRes.text());
    process.exit(1);
  }
  const tokens = await tokenRes.json();
  assert(!!tokens.access_token && !!tokens.refresh_token, 'Token exchange succeeds, yielding both an access and a refresh token');

  // ===== Step 6: inspect the issued token's claims =====
  const claims = decodeJwtPayload(tokens.access_token);
  assert(claims.iss === `${SUPABASE_URL}/auth/v1`, 'Issuer matches the shared project, same as a regular session token');
  assert(claims.aud === 'authenticated', 'Audience is "authenticated", same as a regular session token');
  assert(claims.sub === canonicalUserId, 'The token\'s sub is EXACTLY the canonical ADVESER user id from the password sign-in - same identity, not a separate OAuth-specific one');
  assert(claims.client_id === CLIENT_ID, "The token carries this app's own client_id, the one OAuth-specific addition");

  // ===== Step 7: does PostgREST resolve auth.uid() from this OAuth-issued token? =====
  // Written into an ISOLATED test table (see setup doc), never
  // public.strategies, specifically so this proof touches no real data
  // regardless of outcome.
  const insertRes = await fetch(`${SUPABASE_URL}/rest/v1/oauth_rls_probe`, {
    method: 'POST',
    headers: {
      apikey: SUPABASE_ANON_KEY,
      Authorization: `Bearer ${tokens.access_token}`,
      'Content-Type': 'application/json',
      Prefer: 'return=representation',
    },
    body: JSON.stringify({ note: 'AUTH-003A-3 OAuth/RLS probe' }),
  });
  const insertBody = await insertRes.json();
  assert(insertRes.status === 201, 'An INSERT using the OAuth-issued token succeeds under RLS (WITH CHECK (user_id = auth.uid()) passed)');
  const probeRowUserId = insertBody?.[0]?.user_id;
  assert(probeRowUserId === canonicalUserId, 'auth.uid() resolved, server-side, to the SAME canonical user id the OAuth token carries - this is the core question Task 2 asks, answered empirically, not assumed');

  // ===== Step 8: a SECOND, unrelated session cannot read this row (ordinary cross-user RLS, now proven under an OAuth-issued token too) =====
  // (Left as a documented manual follow-up: requires a second real test
  // account signed in the same way - see docs/AUTH_003A_OAUTH_CLIENT_SETUP.md.)

  // ===== Cleanup: delete the probe row regardless of outcome =====
  await fetch(`${SUPABASE_URL}/rest/v1/oauth_rls_probe?user_id=eq.${canonicalUserId}`, {
    method: 'DELETE',
    headers: { apikey: SUPABASE_ANON_KEY, Authorization: `Bearer ${tokens.access_token}` },
  });

  console.log(`\n=== OAUTH/RLS COMPATIBILITY RESULTS: ${passed} PASSED, ${failed} FAILED ===`);
  if (failed > 0) process.exit(1);
}

run().catch((err) => {
  console.error('Test crashed:', err);
  process.exit(1);
});
